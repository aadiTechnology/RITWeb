    /// <summary>
    /// This method is used to encode the cell text of autogenerated coloums.
    /// </summary>
    /// <param name="e"></param>
    private void EncodeHtmlCells(GridViewRowEventArgs e)
    {
        TableCellCollection cells = e.Row.Cells;
        int iCnt = 0;
        foreach (TableCell cell in cells)
        {
            if (e.Row.RowType == DataControlRowType.DataRow)
            {

                if (iCnt == 0)
                {

                    if (File.Exists(AppDomain.CurrentDomain.BaseDirectory + cell.Text.Substring(1)))
                    {
                        Image oImage = new Image();
                        oImage.ImageUrl = cell.Text;
                        cell.Controls.Add(oImage);
                        cell.HorizontalAlign = HorizontalAlign.Center;
                    }
                    else
                    {
                        cell.Visible = false;
                        grdStudentRank.HeaderRow.Cells[iCnt].Visible = false;
                    }

                }
                else
                {
                    if (iCnt == 2)
                    {                        
                        cell.Width = Unit.Pixel(360);
                        cell.HorizontalAlign = HorizontalAlign.Left;
                    }
                    else
                    {
                        cell.Width = Unit.Pixel(30);
                        cell.HorizontalAlign = HorizontalAlign.Center;
                    }

                    cell.Text = Server.HtmlDecode(cell.Text);
                    cell.CssClass = "Clspadding";
                }
            }else
                cell.HorizontalAlign = HorizontalAlign.Center;
            iCnt++;
        }
    }
