    /// <summary>
    /// This method is used to get required details of selected academic year.
    /// </summary>
    private void GetDetailsOfSelectedYear()
    {
        if (mbIsOldAttendanceToppersScreen && !IsPostBack)
            miAcademicYearId = Convert.ToInt32(cmbAcademicYrId.SelectedValue);
        else if (mbIsOldAttendanceToppersScreen)
            miAcademicYearId = Convert.ToInt32(cmbAcademicYrId.SelectedValue);

		int iStudentId = Convert.ToInt32(Session[Constants.S_SESSION_STUDENT_ID]);
        miStudentId = StudentBL.GetYearwiseStudentId(miSchoolId, miAcademicYearId, iStudentId);
        miOldStdDivId = SchoolWiseStanderedDivisionTestMasterBL.GetStandardDivisionIdOfYear(miSchoolId, miAcademicYearId, miStudentId);
    }

    /// <summary>
    /// This method is used to fill academic year combo on page load.
    /// </summary>
    private void FillAcademicYearCombo()
    {        
        int iStudentId = Convert.ToInt32(Session[Constants.S_SESSION_STUDENT_ID]);
        if (miAcademicYearId == 0)
            miAcademicYearId = Convert.ToInt32(Session[Constants.S_SESSION_CURRENT_ACADEMIC_YEAR_ID]);
        miStudentId = StudentBL.GetYearwiseStudentId(miSchoolId, miAcademicYearId, iStudentId);
        DataTable oDtYearInfo = SchoolWiseAcademicYearMasterBL.GetPassedAcademicYears(miSchoolId, miStudentId,false);
        if (oDtYearInfo != null && oDtYearInfo.Rows.Count > 0 && oDtYearInfo.Rows[0][0] != DBNull.Value)
            ControlUtility.FillDropDownList(oDtYearInfo, ref cmbAcademicYrId,
                                         "Value_Member",
                                         "Display_Member",
                                         "");
             if (cmbAcademicYrId.Items.Count == 1)
            cmbAcademicYrId.Enabled = false;            
    }

