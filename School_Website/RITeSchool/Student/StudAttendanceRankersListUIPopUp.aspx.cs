    /// <summary>
    /// This function is used to initialise field values
    /// </summary>
    private void InitializeFields()
    {
		InitializeMemberVariables();
		grdStudents.PageSize = Constants.I_GRID_PAGE_COUNT;
        grdStudents.EmptyDataText = S_BLANK_GRID_MESSAGE;
        if (!IsPostBack)
        {
            FillAcademicYearCombo();
            SetControlsDefaultValues();
			hidStdDivId.Value = QueryString["iStandardDivisionId"] ?? "0";

			if (QueryString["bIsOldTopperScreen"] != null)
            {
				mbIsOldAttendanceToppersScreen = QueryString["bIsOldTopperScreen"].ToBool();
                hidmOldAttendanceToppers.Value = mbIsOldAttendanceToppersScreen.ToString();
                if (mbIsOldAttendanceToppersScreen)
                    lblOldAcademicYear.Text = CommonUtility.DisplayAcademicYear(cmbAcademicYrId.SelectedItem.Text);
            }
            else
                hidmOldAttendanceToppers.Value = "false";
        }
        else
        {
            mbIsOldAttendanceToppersScreen = Convert.ToBoolean(hidmOldAttendanceToppers.Value);
        }

        if (!mbIsOldAttendanceToppersScreen)
        {
            tdacademicYr.Visible = false;
            cmbAcademicYrId.Visible = false;
            if (cmbAcademicYrId.Items.Count > 0)
            {
               int iAcademicYearId = Convert.ToInt32(cmbAcademicYrId.SelectedValue);
               string sNewStudent = "True";
               if (Session[Constants.S_SESSION_IS_NEW_ADMISSION] != null)
                   sNewStudent = Session[Constants.S_SESSION_IS_NEW_ADMISSION].ToString();
            }            
        }
    }

    private void ShowStudentAttendance()
    {
        grdStudents.PageSize = Constants.I_GRID_PAGE_COUNT;
        grdStudents.DataSource = StudentBL.GetStudentsMonthWiseAttendance(miSchoolId,miAcademicYearId,miOldStdDivId, 3, 0, "Present Days DESC", 100, 0);
        grdStudents.DataBind();

        grdStudentRank.PageSize = Constants.I_GRID_PAGE_COUNT;
        grdStudentRank.DataSource = StudentBL.GetStudentsMonthWiseAttendance(miSchoolId, miAcademicYearId, miOldStdDivId, 3, miStudentId, "Present Days DESC", 100, 0);
        grdStudentRank.DataBind();
    }

